"""
Contract C6: example JSON for every API response and the AI input/output, generated by fixtures/build.py.

The account is fictional ("demo_finanzas"). Regenerate with: python -m eduhub_shared.fixtures.build
"""
import json
from pathlib import Path
from typing import Any
from pydantic import BaseModel
from eduhub_shared.models import (
    AccountSnapshot,
    AnalysisJob,
    AnalysisReport,
    DraftsResponse,
    ErrorResponse,
    FeatureFlags,
    HealthResponse,
    PublishResult,
    SimulationResult,
    TrendsResponse,
)

FIXTURES_DIR = Path(__file__).resolve().parent
FIXTURE_MODELS: dict[str, type[BaseModel]] = {
    "account_snapshot.json": AccountSnapshot,
    "analysis_report.json": AnalysisReport,
    "analysis_job_queued.json": AnalysisJob,
    "analysis_job_analyzing.json": AnalysisJob,
    "analysis_job_done.json": AnalysisJob,
    "analysis_job_failed.json": AnalysisJob,
    "drafts_response.json": DraftsResponse,
    "publish_result.json": PublishResult,
    "simulation_result.json": SimulationResult,
    "feature_flags.json": FeatureFlags,
    "health.json": HealthResponse,
    "trends_response.json": TrendsResponse,
    "error_not_found.json": ErrorResponse,
}

def load_json(name: str) -> Any:
    """
    Return the parsed content of a fixture file.
    """
    return json.loads((FIXTURES_DIR / name).read_text(encoding="utf-8"))

def load_model[T: BaseModel](name: str, model: type[T]) -> T:
    """
    Load a fixture file and validate it as model.
    """
    return model.model_validate(load_json(name))

def load_snapshot() -> AccountSnapshot:
    """
    Return the fixture AccountSnapshot (AI input).
    """
    return load_model("account_snapshot.json", AccountSnapshot)

def load_report() -> AnalysisReport:
    """
    Return the fixture AnalysisReport (AI output, dashboard data).
    """
    return load_model("analysis_report.json", AnalysisReport)
